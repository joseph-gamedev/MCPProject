"""Generates unreal_kit/tools.py (one Python function per tool, from the schema snapshots) and dist/unreal_kit.zip.

    python Scripts/gen_kit.py

Run after the tool surface changes (RuntimeToolsets.UpdateSchemaSnapshots refreshes the snapshots).
"""

import glob
import json
import keyword
import os
import textwrap
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMAS = os.path.join(HERE, "..", "Plugins", "RuntimeToolsets", "Tests", "Schemas")
KIT = os.path.join(HERE, "unreal_kit")
DIST = os.path.join(HERE, "dist")


def py_name(name):
    return name + "_" if keyword.iskeyword(name) else name


def type_text(schema):
    if not isinstance(schema, dict):
        return "any"
    if "enum" in schema:
        return " | ".join(repr(e) for e in schema["enum"])
    t = schema.get("type", "any")
    if t == "array":
        return f"list[{type_text(schema.get('items', {}))}]"
    if isinstance(t, list):
        return " | ".join(t)
    return {"number": "float", "integer": "int", "boolean": "bool", "string": "str", "object": "dict"}.get(t, t)


def gen_tool(tool):
    name = tool["name"].split(".", 1)[1]
    props = tool.get("input_schema", {}).get("properties", {}) or {}
    required = tool.get("input_schema", {}).get("required", []) or []
    order = [p for p in props if p in required] + [p for p in props if p not in required]
    params, mapping, docs = [], [], []
    for p in order:
        n = py_name(p)
        params.append(n if p in required else f"{n}=None")
        mapping.append((n, p))
        s = props[p]
        d = (s.get("description") or "").replace('"""', "'")
        default = f" Default {json.dumps(s['default'])}." if "default" in s else ""
        req = " Required." if p in required else ""
        docs.append(f"{n} ({type_text(s)}):{req} {d}{default}".strip())
    desc = (tool.get("description") or "").replace('"""', "'")
    doc = desc + ("\n\nArgs:\n" + "\n".join("    " + l for d in docs for l in textwrap.wrap(d, 112, subsequent_indent="    ", break_long_words=False, break_on_hyphens=False)) if docs else "")
    sig = ", ".join(["*"] + params) if params else ""
    body = ["    args = {}"]
    for n, p in mapping:
        body.append(f"    if {n} is not None:\n        args[{p!r}] = {n}")
    body.append(f"    return call({tool['name']!r}, **args)")
    fn = py_name(name)
    return f"def {fn}({sig}):\n" + textwrap.indent('"""' + doc + '\n"""', "    ") + "\n" + "\n".join(body) + "\n"


def main():
    out = ['"""Every runtime tool as a Python function (generated by Scripts/gen_kit.py from the schema snapshots - do not edit).',
           "",
           "    from unreal_kit import tools",
           '    tools.lighting.apply_mood(mood="Noon")',
           '    help(tools.logic)            # the toolset\'s tools and arguments',
           "",
           "Optional arguments left as None are not sent (the tool's default applies). Names that clash with Python get a",
           "trailing underscore (class_, import_, from_ ...).",
           '"""',
           "",
           "from types import SimpleNamespace",
           "",
           "from . import call",
           "",
           ""]
    namespaces = []
    total = 0
    for f in sorted(glob.glob(os.path.join(SCHEMAS, "*.json"))):
        data = json.load(open(f, encoding="utf-8"))
        toolset = os.path.splitext(os.path.basename(f))[0]
        tools = data.get("tools", [])
        if not tools:
            continue
        out.append(f"# {'-' * 66} {toolset}\n")
        names = []
        for t in tools:
            code = gen_tool(t)
            fn = code.split("(", 1)[0][4:]
            out.append(code.replace(f"def {fn}(", f"def _{toolset}_{fn}(", 1))
            out.append("")
            names.append(fn)
            total += 1
        doc = (data.get("description") or toolset).replace('"""', "'").split("\n")[0][:300]
        members = ", ".join(f"{n}=_{toolset}_{n}" for n in names)
        out.append(f"{py_name(toolset)} = SimpleNamespace({members})\n{py_name(toolset)}.__doc__ = {doc!r}\n\n")
        namespaces.append(py_name(toolset))
    out.append(f"TOOLSETS = {namespaces!r}\n")
    with open(os.path.join(KIT, "tools.py"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    os.makedirs(DIST, exist_ok=True)
    zpath = os.path.join(DIST, "unreal_kit.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for fn in sorted(os.listdir(KIT)):
            if fn.endswith(".py"):
                z.write(os.path.join(KIT, fn), f"unreal_kit/{fn}")
    relay = os.path.join(HERE, "..", "..", "Relay", "src")
    if os.path.isdir(relay):  # the relay serves it at /s/<code>/kit.zip (redeploy the relay after changes)
        import shutil
        shutil.copy(zpath, os.path.join(relay, "unreal_kit.zip"))
    print(f"{total} tools in {len(namespaces)} toolsets -> unreal_kit/tools.py; {zpath} ({os.path.getsize(zpath) // 1024} KB)")


if __name__ == "__main__":
    main()
